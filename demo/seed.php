<?php

declare(strict_types=1);

/**
 * Creates and fills the fixture tables the demo's `ads` page reads from.
 *
 * Same tables, same driver detection as `tests/Support/DatabaseTestCase.php`
 * — `ra_test_companies`, `ra_test_users`, `ra_test_ads` and `ra_test_tags` —
 * with four columns on `ra_test_ads` that a unit test does not need but this
 * page's worked example does: `created_at` for the sortable date column and
 * the form's hidden `@now` field, `description` for a textarea, `featured` for
 * a checkbox and `published_on` for a date field. Running the test suite
 * afterwards is still safe: `DatabaseTestCase::createFixtures()` drops and
 * recreates every one of these tables before each test that needs them, so it
 * never sees this script's extra columns or its extra rows.
 *
 * `ra_test_ads.id` is a generated key — `AUTO_INCREMENT` on MySQL,
 * `GENERATED BY DEFAULT AS IDENTITY` on PostgreSQL — because the form on that
 * page creates rows and nothing in a create form supplies a primary key. The
 * seed rows below still name their own ids, so the tags can point at them, and
 * the identity is then restarted past the last of them: a PostgreSQL identity
 * column does not notice an explicitly inserted value, so without the restart
 * the first row created through the form would collide with ad 1.
 *
 * Run it once, against whichever server is configured:
 *
 *     php demo/seed.php
 *
 * It reads the same `RA_TEST_MYSQL_*` / `RA_TEST_PGSQL_*` variables the test
 * suite does, seeds every server it finds configured, and says plainly when
 * it finds none — the same honesty `demo/index.php` shows on the page itself
 * when nothing is configured.
 */

require __DIR__ . '/../vendor/autoload.php';

use RockAdmin\Db\Connection;
use RockAdmin\Db\Migrator;
use RockAdmin\Db\Sql;

/**
 * The three administrators the demo signs in as, one per role in
 * `demo/config/roles.php`.
 *
 * They exist so the difference a role makes is something you can look at
 * rather than something you read about: the superadmin sees every control, the
 * editor sees everything except Delete, and the viewer sees the grid with no
 * create button, no edit links and no actions column at all.
 *
 * One password for all three, printed by this script, because this is a demo
 * against a throwaway fixture database. A real installation creates its first
 * administrator through `_setup` (specification 11.4) and never has a password
 * in a file that ships.
 *
 * `roles` and `workspaces` are JSON columns holding lists of strings —
 * `SqlAuthenticator` refuses anything else rather than coercing it, so a
 * `{"editor":true}` here would stop the login with an explanation instead of
 * quietly producing a user with no permissions. Workspaces are the next
 * milestone's, so the lists are empty; an empty list is "no workspace scope",
 * which is what every page in this demo is.
 */
const DEMO_PASSWORD = 'rockadmin';

/** @return list<array{email: string, name: string, roles: list<string>, workspaces: list<string>}> */
function demoUsers(): array
{
    return [
        // Three people, three arrangements of workspace access, because the
        // interesting cases are all about who sees which rows:
        //
        // - Alena holds both, so she gets the switcher *and* the "all
        //   workspaces" option, which 9.3 offers only to somebody who could
        //   reach every row through the switcher anyway.
        // - Bohdan holds one. No switcher at all -- there is nothing to
        //   choose -- and the boundary is invisible to him, which is what it
        //   should be when you only have one.
        // - Cecilie holds the other one, so the two of them looking at
        //   /p/ads see entirely different ads.
        [
            'email' => 'super@example.com',
            'name' => 'Alena Superadmin',
            'roles' => ['superadmin'],
            'workspaces' => ['cyklobazar', 'motobazar'],
        ],
        [
            'email' => 'editor@example.com',
            'name' => 'Bohdan Editor',
            'roles' => ['editor'],
            'workspaces' => ['cyklobazar'],
        ],
        [
            'email' => 'viewer@example.com',
            'name' => 'Cecilie Viewer',
            'roles' => ['viewer'],
            'workspaces' => ['motobazar'],
        ],
    ];
}

/**
 * Creates the `ra_*` tables and puts the three administrators in `ra_users`.
 *
 * `Migrator` first, because nothing below has a table to write to otherwise,
 * and it is the same class `rockadmin migrate` calls — the demo does not get
 * its own DDL, or the shipped schema would have two spellings.
 *
 * Re-runnable, like the rest of this script: the three rows are deleted by
 * address and inserted again, so a second run replaces them rather than
 * failing on the unique index. `ra_login_attempts` is emptied with them,
 * because the throttle is a table and a run of failed attempts from an earlier
 * session would otherwise refuse a correct password on a freshly seeded
 * database — which reads exactly like a broken seed.
 */
function seedAdministrators(Connection $connection): void
{
    (new Migrator($connection))->migrate();

    foreach (demoUsers() as $user) {
        $connection->execute(new Sql('DELETE FROM ra_users WHERE email = ?', [$user['email']]));
        $connection->execute(new Sql('DELETE FROM ra_login_attempts WHERE email = ?', [$user['email']]));

        $connection->execute(new Sql(
            'INSERT INTO ra_users (email, password, name, is_active, roles, workspaces, created_at) '
                . 'VALUES (?, ?, ?, ?, ?, ?, ?)',
            [
                $user['email'],
                // Argon2id, and PHP itself: `password_hash()` with
                // PASSWORD_ARGON2ID is the whole of it, which is why rule 1
                // holds without a package.
                password_hash(DEMO_PASSWORD, PASSWORD_ARGON2ID),
                $user['name'],
                true,
                json_encode($user['roles'], JSON_THROW_ON_ERROR),
                json_encode($user['workspaces'], JSON_THROW_ON_ERROR),
                gmdate('Y-m-d H:i:s'),
            ],
        ));
    }
}

/** @return array{dsn: string, user: ?string, password: ?string}|null */
function seedServerConfig(string $prefix): ?array
{
    $dsn = getenv("RA_TEST_{$prefix}_DSN");

    if (!is_string($dsn) || $dsn === '') {
        return null;
    }

    $user = getenv("RA_TEST_{$prefix}_USER");
    $password = getenv("RA_TEST_{$prefix}_PASSWORD");

    return [
        'dsn' => $dsn,
        'user' => is_string($user) ? $user : null,
        'password' => is_string($password) ? $password : null,
    ];
}

/** @param array{dsn: string, user: ?string, password: ?string} $server */
function seedOneServer(string $label, array $server): void
{
    $pdo = new PDO($server['dsn'], $server['user'], $server['password']);
    $connection = Connection::fromPdo($pdo);
    $mysql = $connection->dialect()->name() === 'mysql';
    $json = $mysql ? 'JSON' : 'JSONB';
    $key = $mysql
        ? 'INTEGER AUTO_INCREMENT PRIMARY KEY'
        : 'INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY';
    $boolean = $mysql ? 'TINYINT(1)' : 'BOOLEAN';
    $false = $mysql ? '0' : 'FALSE';

    foreach (['ra_test_tags', 'ra_test_ads', 'ra_test_users', 'ra_test_companies'] as $table) {
        $connection->execute(new Sql("DROP TABLE IF EXISTS {$table}"));
    }

    foreach ([
        'CREATE TABLE ra_test_companies (id INTEGER PRIMARY KEY, name VARCHAR(100) NOT NULL)',
        'CREATE TABLE ra_test_users (id INTEGER PRIMARY KEY, company_id INTEGER, '
            . 'name VARCHAR(100) NOT NULL, email VARCHAR(100))',
        // `tenant_id` is the workspace boundary (spec 9.3). Every ad belongs
        // to one of the two sites `demo/config/workspaces.php` declares, and
        // the page's `scope` is what keeps one site's ads out of the other's
        // grid -- in the WHERE, where a URL cannot reach it.
        "CREATE TABLE ra_test_ads (id {$key}, tenant_id INTEGER NOT NULL DEFAULT 1, user_id INTEGER, "
            . 'title VARCHAR(200) NOT NULL, description TEXT, price INTEGER, state VARCHAR(20), '
            . "featured {$boolean} NOT NULL DEFAULT {$false}, published_on DATE, stats {$json}, "
            // `photo` holds a storage key -- `ads/2026/10/<32 hex>.jpg` --
            // and never a path or a URL. 255 is what `StorageKey` allows at
            // most, so the column cannot truncate one.
            . 'photo VARCHAR(255), created_at TIMESTAMP)',
        'CREATE TABLE ra_test_tags (id INTEGER PRIMARY KEY, ad_id INTEGER, label VARCHAR(50))',
    ] as $ddl) {
        $connection->execute(new Sql($ddl));
    }

    foreach ([
        ['INSERT INTO ra_test_companies (id, name) VALUES (?, ?)', [1, 'Velo Ltd.']],
        ['INSERT INTO ra_test_companies (id, name) VALUES (?, ?)', [2, 'Moto Ltd.']],
        ['INSERT INTO ra_test_users (id, company_id, name, email) VALUES (?, ?, ?, ?)',
            [1, 1, 'Jana Novak', 'jana@example.com']],
        ['INSERT INTO ra_test_users (id, company_id, name, email) VALUES (?, ?, ?, ?)',
            [2, 2, 'Petr Dvorak', 'petr@example.com']],
    ] as [$text, $bindings]) {
        $connection->execute(new Sql($text, $bindings));
    }

    $states = ['active', 'active', 'draft', 'active', 'sold'];
    // English, like everything else in this repository: the demo is what the
    // screenshots in the README are taken from, and a reader who does not
    // speak Czech should be able to tell what a column holds.
    $titles = [
        'Mountain bike', 'Road bike', 'Scooter', 'Electric bike', 'Kick scooter',
        "Children's bike", 'Trekking bike', 'BMX', 'Honda motorcycle', 'Bike trailer',
        'Cycling computer', 'Giro helmet',
    ];

    $adId = 1;
    $tagId = 1;

    foreach ($titles as $index => $title) {
        $userId = $index % 2 === 0 ? 1 : 2;
        $price = 5000 + $index * 1750;
        $state = $states[$index % count($states)];
        $stats = json_encode(['daily' => ['views' => 3 + $index * 7]], JSON_THROW_ON_ERROR);
        $createdAt = (new DateTimeImmutable('-' . $index . ' days'))->format('Y-m-d H:i:s');
        $publishedOn = $state === 'draft'
            ? null
            : (new DateTimeImmutable('-' . $index . ' days'))->format('Y-m-d');

        $connection->execute(new Sql(
            'INSERT INTO ra_test_ads (id, tenant_id, user_id, title, description, price, state, '
                . 'featured, published_on, stats, created_at) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)',
            [
                $adId,
                // Alternating, so both workspaces have rows and switching
                // visibly changes the grid rather than looking broken.
                $index % 2 === 0 ? 1 : 2,
                $userId,
                $title,
                "{$title} \u{2014} a seeded description, so the textarea has something to draw.",
                $price,
                $state,
                $index % 4 === 0,
                $publishedOn,
                $stats,
                $createdAt,
            ],
        ));

        foreach (array_slice(['used', 'sale', 'new-in', 'free-delivery'], 0, $index % 3) as $tagLabel) {
            $connection->execute(new Sql(
                'INSERT INTO ra_test_tags (id, ad_id, label) VALUES (?, ?, ?)',
                [$tagId++, $adId, $tagLabel],
            ));
        }

        $adId++;
    }

    // The rows above named their own ids, which a PostgreSQL identity column
    // does not notice: its sequence is still at 1, so the first ad created
    // through the demo's form would collide with ad 1. MySQL advances
    // AUTO_INCREMENT past an explicit value on its own, but is restarted here
    // too so both servers hand out the same next key.
    $connection->execute(new Sql($mysql
        ? 'ALTER TABLE ra_test_ads AUTO_INCREMENT = ' . $adId
        : 'ALTER TABLE ra_test_ads ALTER COLUMN id RESTART WITH ' . $adId));

    seedAdministrators($connection);

    echo "Seeded {$label}: " . count($titles) . ' ads, ' . count(demoUsers()) . " administrators.\n";

    foreach (demoUsers() as $user) {
        echo '  ' . $user['email'] . ' / ' . DEMO_PASSWORD
            . ' (' . implode(', ', $user['roles']) . ")\n";
    }
}

$found = false;

foreach (['mysql' => 'MYSQL', 'pgsql' => 'PGSQL'] as $label => $prefix) {
    $server = seedServerConfig($prefix);

    if ($server !== null) {
        $found = true;
        seedOneServer($label, $server);
    }
}

if (!$found) {
    echo 'No database configured. Set RA_TEST_MYSQL_DSN (and, optionally, RA_TEST_PGSQL_DSN) '
        . "before running this script -- the same variables the test suite reads.\n";
    exit(1);
}
