/**
 * The demo's photograph, from the form to the grid and back out again.
 *
 * `DemoFormTest`'s sibling, and over the same shipped configuration -- this
 * one follows the one path the others leave out: a file is uploaded, a key
 * lands in the column, the grid turns that key into a signed address, and the
 * route behind the address hands the bytes back.
 *
 * It is here because every piece of that was tested on its own and the join
 * is where this sort of thing breaks: a column holding a URL instead of a
 * key, a grid showing the key as text, a link nobody can follow. One test
 * that walks the whole way is worth more than four that each watch one step.
 *
 * `#[CoversNothing]`, like its sibling: what it covers is the demo's
 * configuration, which is not a class.
 */
#[CoversNothing]
final class DemoFileTest extends DatabaseTestCase
{
    private SessionStore $session;

    private string $storageRoot;

    protected function setUp(): void
    {
        parent::setUp();

        $this->session = new ArraySessionStore();
        $this->storageRoot = str_replace(DIRECTORY_SEPARATOR, '/', sys_get_temp_dir())
            . '/ra-demo-photo-' . bin2hex(random_bytes(6));

        foreach (self::connections() as [$connection]) {
            if ($connection !== null) {
                $this->createDemoFixture($connection);
            }
        }
    }

    protected function tearDown(): void
    {
        foreach (self::connections() as [$connection]) {
            if ($connection !== null) {
                $this->createFixtures($connection);
            }
        }

        self::removeDirectory($this->storageRoot);

        parent::tearDown();
    }

    private static function removeDirectory(string $path): void
    {
        if (is_dir($path)) {
            foreach (scandir($path) ?: [] as $entry) {
                if ($entry !== '.' && $entry !== '..') {
                    self::removeDirectory($path . '/' . $entry);
                }
            }

            @rmdir($path);

            return;
        }

        if (is_file($path)) {
            @unlink($path);
        }
    }

    /** `demo/seed.php`'s own DDL, `photo` column and all. */
    private function createDemoFixture(Connection $connection): void
    {
        $this->dropFixtures($connection);

        $mysql = $connection->dialect()->name() === 'mysql';
        $json = $mysql ? 'JSON' : 'JSONB';
        $key = $mysql
            ? 'INTEGER AUTO_INCREMENT PRIMARY KEY'
            : 'INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY';
        $boolean = $mysql ? 'TINYINT(1)' : 'BOOLEAN';
        $false = $mysql ? '0' : 'FALSE';

        $connection->execute(new Sql(
            'CREATE TABLE ra_test_users (id INTEGER PRIMARY KEY, company_id INTEGER, '
            . 'name VARCHAR(100) NOT NULL, email VARCHAR(100))',
        ));
        $connection->execute(new Sql(
            "CREATE TABLE ra_test_ads (id {$key}, tenant_id INTEGER NOT NULL DEFAULT 1, user_id INTEGER, "
            . 'title VARCHAR(200) NOT NULL, description TEXT, price INTEGER, state VARCHAR(20), '
            . "featured {$boolean} NOT NULL DEFAULT {$false}, published_on DATE, stats {$json}, "
            . 'photo VARCHAR(255), created_at TIMESTAMP)',
        ));
        $connection->execute(new Sql(
            'CREATE TABLE ra_test_tags (id INTEGER PRIMARY KEY, ad_id INTEGER, label VARCHAR(50))',
        ));
        $connection->execute(new Sql(
            'INSERT INTO ra_test_users (id, company_id, name, email) VALUES (?, ?, ?, ?)',
            [1, 1, 'Jana', 'jana@example.com'],
        ));
    }

    // -- the wiring, as demo/index.php does it -------------------------

    private function urls(): UrlGenerator
    {
        return new UrlGenerator('/');
    }

    private function links(): FileLink
    {
        return new FileLink($this->session);
    }

    private function storage(): Storage
    {
        return new LocalStorage($this->storageRoot, $this->urls(), '', $this->links());
    }

    private function repository(): PageRepository
    {
        $root = \dirname(__DIR__, 3) . '/demo/config';
        $env = static fn (string $name): ?string => null;
        $config = (new Loader($root, $env))->load();

        return new PageRepository($root . '/pages', $env, $config->enums());
    }

    private function requestScope(): RequestScope
    {
        $workspaces = Workspaces::fromConfig(
            (new Loader(\dirname(__DIR__, 3) . '/demo/config', static fn (string $n): ?string => null))
                ->load()
                ->workspaces(),
            $this->repository(),
        );

        return new RequestScope(
            new SessionWorkspace(new ArraySessionStore(), $workspaces),
            Access::identityFor(Access::user(workspaces: ['cyklobazar'])),
        );
    }

    private function region(Connection $connection): FormRegion
    {
        return new FormRegion(
            new RowReader(new SqlRowSource($connection)),
            $this->urls(),
            new Csrf($this->session),
            Access::gateFor($this->repository()),
            Access::identity(),
            $this->requestScope(),
            $this->storage(),
        );
    }

    private function forms(Connection $connection): FormHandler
    {
        $urls = $this->urls();

        return new FormHandler(
            $this->repository(),
            $this->region($connection),
            new Renderer(new TemplateResolver([]), new Escaper(), $urls),
            new Assets($urls),
            new FlashBag($this->session),
            $urls,
            'RockAdmin Demo',
            'auto',
        );
    }

    private function actions(Connection $connection): ActionHandler
    {
        $urls = $this->urls();
        $csrf = new Csrf($this->session);

        return new ActionHandler(
            $this->repository(),
            $this->region($connection),
            // The demo's own limits: 2 MB, and three image types.
            new FieldValidator(UploadLimits::fromConfig(
                (new Loader(\dirname(__DIR__, 3) . '/demo/config', static fn (string $n): ?string => null))->load(),
            )),
            new SqlWriteHandler($connection),
            new RowReader(new SqlRowSource($connection)),
            $this->requestScope(),
            $connection,
            $this->forms($connection),
            $csrf,
            new FlashBag($this->session),
            $urls,
            null,
            null,
            null,
            null,
            null,
            new FileWrites($this->storage()),
        );
    }

    /**
     * The demo's grid, rendered the way `demo/index.php` builds it.
     */
    private function grid(Connection $connection): string
    {
        $rows = new SqlRowSource($connection);
        $urls = $this->urls();

        $region = new ListRegion(
            $rows,
            new QueryFactory(scope: $this->requestScope()),
            new CellFormatter($this->storage()),
            $urls,
            Access::gateFor($this->repository()),
            Access::identity(),
            new Csrf($this->session),
            $this->requestScope(),
        );

        $page = $this->repository()->get('ads');
        $grid = $page->region('grid');
        $view = $region->render($page, $grid, GridState::fromQuery([], $grid->key, $grid));

        return (new Renderer(new TemplateResolver([]), new Escaper(), $urls))
            ->render('region/list/region', $view);
    }

    /**
     * An upload as PHP hands one over: a temporary file, and whatever the
     * browser claimed about it -- which nothing here believes.
     */
    private function upload(string $contents, string $name = 'kolo.png'): UploadedFile
    {
        $path = tempnam(sys_get_temp_dir(), 'ra-upload-');

        self::assertIsString($path);
        file_put_contents($path, $contents);

        return new UploadedFile($name, $path, \strlen($contents));
    }

    /** A one-pixel PNG, signature and all: the type is read from these bytes. */
    private static function png(): string
    {
        return base64_decode(
            'iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAYAAAAfFcSJAAAADUlEQVR42mP8z8BQDwAEhQGAhKmMIQAAAABJRU5ErkJggg==',
            true,
        ) ?: '';
    }

    /**
     * @param  array<string, mixed>       $body
     * @param  array<string, UploadedFile> $files
     */
    private function post(Connection $connection, string $action, array $body, array $files = []): Response
    {
        return $this->actions($connection)->handle(
            new Route('action', ['page' => 'ads', 'action' => $action]),
            new Request(
                'POST',
                "a/ads/{$action}",
                body: [Csrf::FIELD => (new Csrf($this->session))->token()] + $body,
                files: $files,
            ),
        );
    }

    /** @param array<string, mixed> $extra */
    private function createAd(Connection $connection, array $extra = []): void
    {
        $response = $this->post($connection, 'create', [
            'title' => 'Horské kolo',
            'price' => '12000',
            'state' => 'active',
        ] + $extra, [
            // Called something else entirely, and nothing reads the name: the
            // type comes from the bytes and the extension from our own table.
            'photo' => $this->upload(self::png(), 'whatever-the-browser-called-it.txt'),
        ]);

        self::assertSame(302, $response->status, 'A create with a valid photo is expected to succeed.');
    }

    /** @return array<string, mixed> */
    private function ad(Connection $connection): array
    {
        $rows = $connection->select(new Sql('SELECT * FROM ra_test_ads ORDER BY id'));

        self::assertCount(1, $rows);

        return $rows[0];
    }

    // -- the whole way through ------------------------------------------

    #[DataProvider('connections')]
    public function testAPhotoUploadedOnTheDemoPageIsStoredUnderAKeyThatPageOwns(?Connection $connection): void
    {
        $connection = $this->requireConnection($connection);

        $this->createAd($connection);

        $key = $this->ad($connection)['photo'];

        self::assertIsString($key);

        // The key, and three things about it, each of which is a decision
        // this milestone made rather than an accident of implementation:
        self::assertStringStartsWith('ads/', $key, 'A key is written under the page that wrote it.');
        self::assertMatchesRegularExpression(
            '#^ads/\d{4}/\d{2}/[0-9a-f]{32}\.png$#',
            $key,
            'The name is random and the extension comes from the bytes, never from the browser.',
        );
        self::assertFileExists($this->storageRoot . '/' . $key);
        self::assertSame(self::png(), file_get_contents($this->storageRoot . '/' . $key));
    }

    #[DataProvider('connections')]
    public function testTheColumnHoldsAKeyAndTheGridDrawsAnAddress(?Connection $connection): void
    {
        $connection = $this->requireConnection($connection);

        $this->createAd($connection);

        $key = $this->ad($connection)['photo'];

        self::assertIsString($key);

        $html = $this->grid($connection);

        // The picture is drawn, and what is drawn is the route, signed --
        // never the column's own value as a path.
        self::assertStringContainsString('ra-grid-cell-photo', $html);
        self::assertStringContainsString('<img', $html);
        self::assertMatchesRegularExpression(
            '#src="/_file/' . preg_quote($key, '#') . '\?[^"]*s=[0-9a-f]{32}#',
            $html,
        );
    }

    #[DataProvider('connections')]
    public function testTheAddressTheGridDrewActuallyServesTheFile(?Connection $connection): void
    {
        $connection = $this->requireConnection($connection);

        $this->createAd($connection);

        $key = $this->ad($connection)['photo'];

        self::assertIsString($key);

        // Followed exactly as a browser would follow it: the URL the storage
        // built, split the way the router splits it.
        $url = $this->storage()->url($key);
        $query = parse_url($url, PHP_URL_QUERY);

        self::assertIsString($query);

        parse_str($query, $parsed);

        $response = (new FileHandler($this->storage(), $this->links()))->handle(
            new Route('file', ['key' => $key]),
            new Request('GET', '_file/' . $key, array_map(
                static fn (mixed $value): mixed => $value,
                $parsed,
            )),
        );

        self::assertSame(200, $response->status);
        self::assertSame('image/png', $response->headers['content-type']);
        self::assertSame(self::png(), $response->body);
    }

    #[DataProvider('connections')]
    public function testReplacingThePhotoForgetsTheOneItReplaced(?Connection $connection): void
    {
        $connection = $this->requireConnection($connection);

        $this->createAd($connection);

        $row = $this->ad($connection);
        $first = $row['photo'];
        $id = $row['id'];

        self::assertIsString($first);
        self::assertIsNumeric($id);

        $response = $this->post($connection, 'update', [
            '_id' => (string) $id,
            'title' => 'Horské kolo',
            'price' => '12000',
            'state' => 'active',
        ], [
            'photo' => $this->upload(self::png() . "\x00second", 'second.png'),
        ]);

        self::assertSame(302, $response->status);

        $second = $this->ad($connection)['photo'];

        self::assertIsString($second);
        self::assertNotSame($first, $second);
        self::assertFileExists($this->storageRoot . '/' . $second);
        self::assertFileDoesNotExist(
            $this->storageRoot . '/' . $first,
            'The replaced file is forgotten after the commit, not left as an orphan.',
        );
    }

    #[DataProvider('connections')]
    public function testAFileTheInstallationDoesNotAllowIsRefusedAndNothingIsWritten(?Connection $connection): void
    {
        $connection = $this->requireConnection($connection);

        // A PDF: a type `uploads.types` knows about but this demo's
        // configuration deliberately leaves out, and the field narrows
        // further to JPEG and PNG.
        $response = $this->post($connection, 'create', [
            'title' => 'Horské kolo',
            'price' => '12000',
            'state' => 'active',
        ], [
            'photo' => $this->upload('%PDF-1.4 and the rest', 'scan.pdf'),
        ]);

        self::assertSame(422, $response->status, 'A refused upload re-renders the form.');
        self::assertSame([], $connection->select(new Sql('SELECT * FROM ra_test_ads')));
        self::assertDirectoryDoesNotExist(
            $this->storageRoot . '/ads',
            'Nothing is stored when the write did not happen.',
        );
    }
}
