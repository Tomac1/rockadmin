<?php

declare(strict_types=1);

namespace RockAdmin\Tests\Integration\Form;

use PHPUnit\Framework\Attributes\CoversNothing;
use PHPUnit\Framework\Attributes\DataProvider;
use RockAdmin\Auth\Gate;
use RockAdmin\Auth\Permission;
use RockAdmin\Auth\Roles;
use RockAdmin\Config\Loader;
use RockAdmin\Db\Connection;
use RockAdmin\Db\Sql;
use RockAdmin\Db\SqlRowSource;
use RockAdmin\Grid\CellFormatter;
use RockAdmin\Grid\GridState;
use RockAdmin\Grid\ListRegion;
use RockAdmin\Grid\QueryFactory;
use RockAdmin\Http\ArraySessionStore;
use RockAdmin\Http\Csrf;
use RockAdmin\Http\UrlGenerator;
use RockAdmin\Page\PageRepository;
use RockAdmin\Tests\Support\Access;
use RockAdmin\Tests\Support\DatabaseTestCase;

/**
 * The demo's actions, rendered against its own configuration and a real grid.
 *
 * Task 7 of milestone 8 asks for this to be driven in a browser and for what
 * was measured to be reported. It was, and this file is what keeps that one
 * look from being the only thing standing behind it: the demo is the worked
 * example the documentation points at, and the thing most likely to break it
 * is a permission change nobody traced through to what gets drawn.
 *
 * What is checked here is the part a browser pass cannot repeat cheaply for
 * every role: that the gate decides what exists, rather than CSS hiding it.
 * Specification 9.2 — a visible control that answers 403 is a bug, not a
 * safeguard — and its converse, which is the one that actually bites: a
 * control drawn for somebody who may not use it.
 *
 * `#[CoversNothing]`, because it covers the demo's configuration and that is
 * not a class.
 */
#[CoversNothing]
final class DemoActionsTest extends DatabaseTestCase
{
    protected function setUp(): void
    {
        parent::setUp();

        foreach (self::connections() as [$connection]) {
            if ($connection !== null) {
                $this->createDemoFixture($connection);
            }
        }
    }

    protected function tearDown(): void
    {
        // `DatabaseTestCase`'s own fixtures back exactly as they were, for
        // whatever runs next. The demo's page names `ra_test_ads` in a file
        // that ships, so this cannot use a uniquely named table of its own
        // without testing a copy of the configuration instead of the
        // configuration.
        foreach (self::connections() as [$connection]) {
            if ($connection !== null) {
                $this->createFixtures($connection);
            }
        }

        parent::tearDown();
    }

    /**
     * The demo's own table shape, with three states in it.
     *
     * `active`, `draft` and `sold` are all here on purpose: the condition on
     * `archive` is only proved by a grid holding rows on both sides of it, and
     * a fixture of three active ads would let a broken `when` pass.
     */
    private function createDemoFixture(Connection $connection): void
    {
        $this->dropFixtures($connection);

        $mysql = $connection->dialect()->name() === 'mysql';
        $json = $mysql ? 'JSON' : 'JSONB';
        $key = $mysql
            ? 'INTEGER AUTO_INCREMENT PRIMARY KEY'
            : 'INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY';
        $boolean = $mysql ? 'TINYINT(1)' : 'BOOLEAN';
        $false = $mysql ? '0' : 'FALSE';

        $connection->execute(new Sql(
            'CREATE TABLE ra_test_users (id INTEGER PRIMARY KEY, company_id INTEGER, '
            . 'name VARCHAR(100) NOT NULL, email VARCHAR(100))',
        ));
        $connection->execute(new Sql(
            "CREATE TABLE ra_test_ads (id {$key}, user_id INTEGER, "
            . 'title VARCHAR(200) NOT NULL, description TEXT, price INTEGER, state VARCHAR(20), '
            . "featured {$boolean} NOT NULL DEFAULT {$false}, published_on DATE, stats {$json}, "
            . 'created_at TIMESTAMP)',
        ));
        $connection->execute(new Sql(
            'CREATE TABLE ra_test_tags (id INTEGER PRIMARY KEY, ad_id INTEGER, label VARCHAR(50))',
        ));
        $connection->execute(new Sql(
            'INSERT INTO ra_test_users (id, company_id, name, email) VALUES (?, ?, ?, ?)',
            [1, 1, 'Jana', 'jana@example.com'],
        ));

        foreach ([[1, 'Horské kolo', 'active'], [2, 'Silniční kolo', 'draft'], [3, 'Skútr', 'sold']] as [$id, $title, $state]) {
            $connection->execute(new Sql(
                'INSERT INTO ra_test_ads (id, user_id, title, price, state, stats, created_at) '
                . 'VALUES (?, ?, ?, ?, ?, ?, ?)',
                [$id, 1, $title, 5000, $state, '{"daily":{"views":3}}', '2026-10-01 10:00:00'],
            ));
        }
    }

    #[DataProvider('connections')]
    public function testAViewerIsOfferedOnlyWhatChangesNothing(?Connection $connection): void
    {
        // `ads.view` and nothing else. The two `open` controls declare
        // `ads.view` and stay — reading a row is what a viewer is for — and
        // every control that writes is gone. The selection column goes with
        // them: it exists to feed bulk actions, and a viewer has none.
        $view = $this->grid($this->require($connection), ['ads.view']);

        $this->assertSame(
            ['peek', 'peek_modal'],
            $this->actionKeys($view),
            'A viewer was offered a control that writes, or lost one that only reads.',
        );
        $this->assertFalse(
            $view->isSelectable(),
            'A viewer got a selection column feeding controls they have not got.',
        );
    }

    #[DataProvider('connections')]
    public function testAnEditorIsOfferedEditAndArchiveButNotDelete(?Connection $connection): void
    {
        // `ads.update` and not `ads.delete`. The demo's `bin` action declares
        // `ads.delete`, so it is the one that must not appear -- and its
        // absence has to come from the gate, not from the template.
        $view = $this->grid($this->require($connection), ['ads.view', 'ads.update']);

        $keys = $this->actionKeys($view);

        $this->assertContains('edit', $keys);
        $this->assertContains('archive', $keys);
        $this->assertNotContains('bin', $keys);
    }

    #[DataProvider('connections')]
    public function testArchiveIsNotOfferedOnARowThatIsNotActive(?Connection $connection): void
    {
        // The demo's `archive` carries `when: state = active`. Its own seed
        // writes a sold ad and a draft one, so this is a real row rather than
        // a fixture invented to make the condition true.
        $view = $this->grid($this->require($connection), ['ads.*']);

        $withArchive = 0;
        $without = 0;

        foreach ($view->rows as $row) {
            $keys = $this->keysOfRow($row);

            if (\in_array('archive', $keys, true)) {
                $withArchive++;

                continue;
            }

            $without++;

            // Whatever else it lost, it kept the two that have no condition.
            $this->assertContains('edit', $keys);
            $this->assertContains('bin', $keys);
        }

        $this->assertGreaterThan(0, $withArchive, 'No row offered archive, so the condition proves nothing.');
        $this->assertGreaterThan(0, $without, 'Every row offered archive, so the condition is not being applied.');
    }

    #[DataProvider('connections')]
    public function testOnlyTheBulkActionsThePageListsAreOffered(?Connection $connection): void
    {
        // `edit` is a link and is deliberately not in `bulk_actions`: there is
        // no such thing as editing forty rows at once.
        $view = $this->grid($this->require($connection), ['ads.*']);

        $keys = array_map(static fn ($action): string => $action->key, $view->bulkActions);

        $this->assertSame(['archive', 'bin'], $keys);
    }

    #[DataProvider('connections')]
    public function testEveryBulkControlCarriesAConfirmationAndAToken(?Connection $connection): void
    {
        // Spec 8.5 confirms every `post`, and the loader refuses one without a
        // `confirm`. This is the other end of that: what was configured
        // actually reached the control.
        $view = $this->grid($this->require($connection), ['ads.*']);

        $this->assertNotSame('', $view->bulkToken);

        foreach ($view->bulkActions as $action) {
            $this->assertTrue($action->isPost);
            $this->assertNotSame('', $action->confirm, "Bulk action '{$action->key}' asks nothing.");
        }
    }

    #[DataProvider('connections')]
    public function testTheGridDrawsNoEditCellOfItsOwnBesideAnActionsColumn(?Connection $connection): void
    {
        // The demo declares a `tools` column, so the grid's own trailing Edit
        // cell is not drawn: a page that says where its row controls go has
        // said it. Two Edit controls in a row, one configured and one not,
        // leaves a project no way to remove the second.
        $view = $this->grid($this->require($connection), ['ads.*']);

        $this->assertFalse($view->hasRowActions());

        foreach ($view->rows as $row) {
            $this->assertNull($row->editUrl);
        }
    }

    // --- harness ---

    private function require(?Connection $connection): Connection
    {
        if ($connection === null) {
            $this->markTestSkipped('No connection configured.');
        }

        return $connection;
    }

    /** @param list<string> $permissions */
    private function grid(Connection $connection, array $permissions): \RockAdmin\Grid\ListView
    {
        $pages = $this->repository();
        $page = $pages->get('ads');
        $region = $page->regions['grid'];

        $urls = new UrlGenerator('/');
        $gate = new Gate(
            Roles::fromConfig(
                [Access::ROLE => ['permissions' => $permissions]],
                Permission::catalogue($pages),
            ),
            $pages,
        );

        $list = new ListRegion(
            new SqlRowSource($connection),
            new QueryFactory(),
            new CellFormatter(),
            $urls,
            $gate,
            Access::identity(),
            new Csrf(new ArraySessionStore()),
        );

        return $list->render($page, $region, GridState::fromQuery([], $region->key, $region));
    }

    /** @return list<string> every action key drawn anywhere in the grid's rows */
    private function actionKeys(\RockAdmin\Grid\ListView $view): array
    {
        $keys = [];

        foreach ($view->rows as $row) {
            foreach ($this->keysOfRow($row) as $key) {
                if (!\in_array($key, $keys, true)) {
                    $keys[] = $key;
                }
            }
        }

        sort($keys);

        return $keys;
    }

    /** @return list<string> */
    private function keysOfRow(\RockAdmin\Grid\RowView $row): array
    {
        $keys = [];

        foreach ($row->cells as $cell) {
            foreach ($cell->actions as $action) {
                $keys[] = $action->key;
            }
        }

        return $keys;
    }

    private function repository(): PageRepository
    {
        $root = \dirname(__DIR__, 3) . '/demo/config';
        $env = static fn (string $name): ?string => null;
        $config = (new Loader($root, $env))->load();

        return new PageRepository($root . '/pages', $env, $config->enums());
    }
}
